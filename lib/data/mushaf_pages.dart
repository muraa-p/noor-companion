  /// Returns the mushaf page number (1..604) for a given global ayah number (1..6236).
  static int pageOfGlobalAyah(int globalAyah) {
    for (int i = 0; i < pageStarts.length; i++) {
      final startSurah = pageStarts[i][0];
      final startAyah = pageStarts[i][1];
      final startGlobal = _globalNumber(startSurah, startAyah);
      if (i == pageStarts.length - 1) {
        if (globalAyah >= startGlobal) return i + 1;
      } else {
        final nextSurah = pageStarts[i + 1][0];
        final nextAyah = pageStarts[i + 1][1];
        final nextGlobal = _globalNumber(nextSurah, nextAyah);
        if (globalAyah >= startGlobal && globalAyah < nextGlobal) return i + 1;
      }
    }
    return 1;
  }

  static int _globalNumber(int surah, int ayah) {
    var n = ayah;
    for (var s = 1; s < surah; s++) {
      n += AyahGlobals.ayahCounts[s - 1];
    }
    return n;
  }
